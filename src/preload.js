  unshareBuild: (id) => ipcRenderer.invoke('unshareBuild', id),
  browseBuilds: (heroKey) => ipcRenderer.invoke('browseBuilds', heroKey),
  importBuild: (remoteId) => ipcRenderer.invoke('importBuild', remoteId),
  metaFiles: () => ipcRenderer.invoke('metaFiles'),
  metaOverview: (key) => ipcRenderer.invoke('metaOverview', key),
